#!/usr/bin/env python3
"""Build Dragon Clash's gear art from the drawn pieces.

  python3 tools/build_gear.py

Put your exported PNGs in assets/gear/src/, named as docs/GEAR-ASSETS.md lists them
(armor-<set>-<piece>.png, weapon-<name>-<piece>.png, fx-<ability>-<n>.png, icon-<thing>.png).
Body pieces (960x960) are downscaled to 480x480, the tail mace (512) to 256, so the game loads less.
Output: assets/gear/*.png and assets/gear/gear.js (the manifest js/art.js reads). Any piece not present keeps
its placeholder in the game.
"""
import glob, json, os, re
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'assets', 'gear', 'src')
OUT = os.path.join(HERE, '..', 'assets', 'gear')
NAME = re.compile(r'^(armor-(scale|iron|bone)-[a-z-]+|weapon-[a-z-]+|fx-[a-z]+(-[a-z]+)?-\d+|icon-[a-z]+-[a-z]+)\.png$')

files, skipped = {}, []
for path in sorted(glob.glob(os.path.join(SRC, '*.png'))):
    name = os.path.basename(path).lower()
    if not NAME.match(name):
        skipped.append(name); continue
    im = Image.open(path).convert('RGBA')
    if name.startswith('armor-') or (name.startswith('weapon-') and name != 'weapon-tailmace.png'):
        size = (480, 480)
    elif name == 'weapon-tailmace.png':
        size = (256, 256)
    elif name.startswith('icon-'):
        size = (128, 128)
    else:
        size = (im.width // 2, im.height // 2) if im.width > 256 else im.size
    if im.size != size:
        im = im.resize(size, Image.LANCZOS)
    im.save(os.path.join(OUT, name), optimize=True)
    files[name[:-4]] = name

with open(os.path.join(OUT, 'gear.js'), 'w') as f:
    f.write('/* Generated by tools/build_gear.py. Gear art present; anything missing uses a placeholder. */\n')
    f.write('window.DC_GEAR = ' + json.dumps({'files': files}, indent=1, sort_keys=True) + ';\n')
print('%d pieces built' % len(files))
if skipped:
    print('Skipped (name not recognised):', ', '.join(skipped))
