#!/usr/bin/env node
// Scans games/*/game.json and writes games/registry.js (loaded by the hub with a plain
// <script> tag, so the hub also works when opened as a local file) and games/registry.json
// (for a server or platform that prefers JSON). Run after adding or editing a game:
//   node tools/build-registry.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gamesDir = join(root, 'games');
const REQUIRED = ['id', 'title', 'version', 'entry'];

const games = [];
const problems = [];
for (const dir of readdirSync(gamesDir).sort()) {
  const folder = join(gamesDir, dir);
  if (!statSync(folder).isDirectory()) continue;
  const file = join(folder, 'game.json');
  if (!existsSync(file)) { problems.push(`${dir}: missing game.json`); continue; }
  let m;
  try { m = JSON.parse(readFileSync(file, 'utf8')); } catch (e) { problems.push(`${dir}: game.json is not valid JSON (${e.message})`); continue; }
  const missing = REQUIRED.filter(k => !m[k]);
  if (missing.length) { problems.push(`${dir}: game.json is missing ${missing.join(', ')}`); continue; }
  if (m.id !== dir) problems.push(`${dir}: id "${m.id}" should match the folder name`);
  if (!existsSync(join(folder, m.entry.split('#')[0]))) problems.push(`${dir}: entry ${m.entry} not found`);
  if (m.server && !existsSync(join(folder, m.server))) problems.push(`${dir}: server ${m.server} not found`);
  if (m.status === 'prototype') continue;
  games.push({ ...m, path: `games/${dir}/` });
}

const banner = '// Generated by tools/build-registry.mjs — do not edit by hand.\n';
writeFileSync(join(gamesDir, 'registry.js'), `${banner}window.GAME_REGISTRY = ${JSON.stringify(games, null, 2)};\n`);
writeFileSync(join(gamesDir, 'registry.json'), JSON.stringify({ generated: new Date().toISOString(), games }, null, 2) + '\n');
console.log(`Registry: ${games.length} game(s) — ${games.map(g => g.id).join(', ') || 'none'}`);
if (problems.length) { console.warn('Problems:\n  ' + problems.join('\n  ')); process.exitCode = 1; }
